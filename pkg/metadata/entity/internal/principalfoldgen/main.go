// Command principalfoldgen writes the frozen table FoldPrincipalName keys
// user and group names by. It is run once, under the Unicode version it
// refuses every other version of: the table is part of the store format, and
// a Go release with newer Unicode data must not change it. Rerunning it under
// another version is a key migration of every user and group name row.
//
// The table maps each rune whose simple case-folding orbit holds a smaller
// rune to the smallest rune of that orbit, so two names strings.EqualFold
// calls equal under that Unicode version share one key.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"unicode"
	"unicode/utf8"
)

// frozenVersion is the Unicode version the name rows were first keyed under.
const frozenVersion = "15.0.0"

// pairs is the table: each rune the fold changes, with the least rune of its
// unicode.SimpleFold orbit.
func pairs() [][2]rune {
	var out [][2]rune
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if !utf8.ValidRune(r) {
			continue
		}
		least := r
		for f := unicode.SimpleFold(r); f != r; f = unicode.SimpleFold(f) {
			least = min(least, f)
		}
		if least != r {
			out = append(out, [2]rune{r, least})
		}
	}
	return out
}

func main() {
	if unicode.Version != frozenVersion {
		log.Fatalf("Unicode %s, want %s: run under the toolchain that has it (GOTOOLCHAIN=go1.26.10)", unicode.Version, frozenVersion)
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by internal/principalfoldgen from Unicode %s; DO NOT EDIT.\n\n", unicode.Version)
	b.WriteString("package entity\n\n")
	b.WriteString("// principalFold is FoldPrincipalName's table: each rune whose simple\n")
	b.WriteString("// case-folding orbit holds a smaller rune, mapped to the smallest.\n")
	b.WriteString("var principalFold = map[rune]rune{\n")
	ps := pairs()
	for _, p := range ps {
		fmt.Fprintf(&b, "0x%04X: 0x%04X,\n", p[0], p[1])
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("principal_fold_table.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
	log.Printf("%d mappings", len(ps))
}
