package main

import (
	"bytes"
	"errors"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"go/types"
	"path/filepath"
	"reflect"
	"strconv"
	"strings"
)

// header begins every file the generator writes, and the inputs follow it,
// so a fresh run can be compared with the file checked in (RFC 20 section 5.1).
const header = "// Code generated by nfs/wire/gen from "

const (
	wirePath      = "github.com/cubbit/dittofs/internal/adapter/nfs/wire"
	resourcesPath = "github.com/cubbit/dittofs/pkg/resources"
)

type kind int

const (
	kUint32 kind = iota
	kUint64
	kInt64
	kBool
	kFixed  // [N]byte: a fixed-length opaque
	kVector // [N]T, T of a basic kind: a fixed-length array
	kOpaque // []byte: a variable-length opaque
	kString
	kArray    // []T, T of a basic kind or a struct: a variable-length array
	kOptional // *T, T a struct: optional data
	kStruct
	kVoid // struct{}: a void arm
)

var basics = map[string]kind{"uint32": kUint32, "uint64": kUint64, "int64": kInt64, "bool": kBool}

// xtype is a field's XDR form.
type xtype struct {
	kind kind
	name string // a struct's name, or the named type a basic kind converts to
	n    int    // a fixed length, or a variable one's maximum
	elem *xtype
}

type field struct {
	name  string // "_" for a void arm
	t     *xtype
	since int    // on the wire from this minor version on; 0 in every one
	arm   string // a union arm's case value or "default"; "" for any other field
	pos   token.Pos
}

type strct struct {
	name   string
	union  bool // its first field is the discriminant, every other an arm
	fields []field
}

type gen struct {
	fset    *token.FileSet
	structs []*strct
	byName  map[string]*strct
	named   map[string]kind // the types named over a basic kind
	errs    []error
}

func (g *gen) errorf(pos token.Pos, format string, args ...any) {
	g.errs = append(g.errs, fmt.Errorf("%s: "+format, append([]any{g.fset.Position(pos)}, args...)...))
}

// generate reads files, in dir, and returns the codec of every struct type they
// declare, or every field it cannot honour.
func generate(dir string, files []string) ([]byte, error) {
	g := &gen{fset: token.NewFileSet(), byName: map[string]*strct{}, named: map[string]kind{}}
	var pkg string
	var specs []*ast.TypeSpec
	for _, name := range files {
		f, err := parser.ParseFile(g.fset, filepath.Join(dir, name), nil, 0)
		if err != nil {
			return nil, err
		}
		if pkg == "" {
			pkg = f.Name.Name
		}
		for _, d := range f.Decls {
			if gd, ok := d.(*ast.GenDecl); ok && gd.Tok == token.TYPE {
				for _, s := range gd.Specs {
					specs = append(specs, s.(*ast.TypeSpec))
				}
			}
		}
	}
	for _, s := range specs {
		if id, ok := s.Type.(*ast.Ident); ok {
			if k, ok := basics[id.Name]; ok {
				g.named[s.Name.Name] = k
			}
		}
		if _, ok := s.Type.(*ast.StructType); ok {
			st := &strct{name: s.Name.Name}
			g.structs = append(g.structs, st)
			g.byName[st.name] = st
		}
	}
	if len(g.structs) == 0 {
		return nil, fmt.Errorf("%s: no struct types", strings.Join(files, " "))
	}
	for _, s := range specs {
		if st, ok := s.Type.(*ast.StructType); ok {
			g.parse(g.byName[s.Name.Name], st)
		}
	}
	if len(g.errs) == 0 {
		g.cycles()
	}
	if len(g.errs) > 0 {
		return nil, errors.Join(g.errs...)
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "%s%s; DO NOT EDIT.\n\npackage %s\n\nimport (\n%q\n%q\n)\n", header, strings.Join(files, " "), pkg, wirePath, resourcesPath)
	for _, s := range g.structs {
		g.methods(&b, s)
	}
	return format.Source(b.Bytes())
}

// tag is a field's xdr tag, read.
type tag struct {
	max, since int
	union, def bool
	arm        string
}

func readTag(lit *ast.BasicLit) (tag, error) {
	var t tag
	s := ""
	if lit != nil {
		raw, _ := strconv.Unquote(lit.Value)
		s = reflect.StructTag(raw).Get("xdr")
	}
	if s == "" {
		return t, nil
	}
	for _, opt := range strings.Split(s, ",") {
		key, val, _ := strings.Cut(opt, "=")
		switch key {
		case "max", "since":
			n, err := strconv.Atoi(val)
			if err != nil || n <= 0 {
				return t, fmt.Errorf("%s=%q is not a count above zero", key, val)
			}
			if key == "max" {
				t.max = n
			} else {
				t.since = n
			}
		case "union":
			t.union = true
		case "default":
			t.def = true
		case "case":
			// decision: an arm names one value. XDR lets several cases share
			// an arm (RFC 4506 section 6.3); each is an arm of its own until a
			// union needs them shared.
			v, err := strconv.ParseUint(val, 0, 32)
			if err != nil {
				return t, fmt.Errorf("case=%q is not one uint32", val)
			}
			t.arm = strconv.FormatUint(v, 10)
		default:
			return t, fmt.Errorf("%q is no xdr tag", opt)
		}
	}
	return t, nil
}

func (g *gen) parse(s *strct, st *ast.StructType) {
	for i, f := range st.Fields.List {
		if len(f.Names) == 0 {
			g.errorf(f.Pos(), "%s: an embedded field", s.name)
			continue
		}
		tg, err := readTag(f.Tag)
		for _, id := range f.Names {
			at := s.name + "." + id.Name
			if err != nil {
				g.errorf(id.Pos(), "%s: %v", at, err)
				continue
			}
			t, took, err := g.xdrType(f.Type, tg.max)
			if err != nil {
				g.errorf(id.Pos(), "%s: %v", at, err)
				continue
			}
			if tg.max > 0 && !took {
				g.errorf(id.Pos(), "%s: max on a type of fixed length", at)
			}
			fd := field{name: id.Name, t: t, since: tg.since, arm: tg.arm, pos: id.Pos()}
			if tg.def {
				fd.arm = "default"
			}
			switch {
			case tg.union:
				if i != 0 || len(f.Names) != 1 {
					g.errorf(id.Pos(), "%s: a union's discriminant is its struct's first field", at)
				} else if t.kind != kUint32 || tg.since > 0 {
					g.errorf(id.Pos(), "%s: a discriminant is a uint32 on the wire in every version", at)
				}
				s.union = true
			case !s.union && fd.arm != "":
				g.errorf(id.Pos(), "%s: an arm outside a union", at)
			case s.union && fd.arm == "":
				g.errorf(id.Pos(), "%s: a union's field that is no arm", at)
			case fd.arm == "default" && (tg.arm != "" || tg.since > 0):
				g.errorf(id.Pos(), "%s: a default arm takes no case and no since", at)
			}
			if (t.kind == kVoid) != (id.Name == "_" && fd.arm != "") {
				g.errorf(id.Pos(), "%s: a void arm is a blank field of type struct{}, and only it is", at)
			}
			for _, prev := range s.fields {
				if fd.arm != "" && prev.arm == fd.arm {
					g.errorf(id.Pos(), "%s: a second arm for %s", at, fd.arm)
				}
			}
			s.fields = append(s.fields, fd)
		}
	}
	if s.union && len(s.fields) < 2 {
		g.errorf(st.Pos(), "%s: a union with no arm", s.name)
	}
}

// xdrType reads a field's Go type as its XDR form; max is the bound its tag
// states, 0 for none, and took reports whether a variable-length type took it.
func (g *gen) xdrType(e ast.Expr, max int) (t *xtype, took bool, err error) {
	switch e := e.(type) {
	case *ast.Ident:
		if k, ok := basics[e.Name]; ok {
			return &xtype{kind: k}, false, nil
		}
		if k, ok := g.named[e.Name]; ok {
			return &xtype{kind: k, name: e.Name}, false, nil
		}
		if _, ok := g.byName[e.Name]; ok {
			return &xtype{kind: kStruct, name: e.Name}, false, nil
		}
		if e.Name == "string" {
			if max == 0 {
				return nil, false, errors.New("a string with no maximum: tag it max=N")
			}
			return &xtype{kind: kString, n: max}, true, nil
		}
	case *ast.ArrayType:
		byteElem := false
		if id, ok := e.Elt.(*ast.Ident); ok {
			byteElem = id.Name == "byte" || id.Name == "uint8"
		}
		if e.Len != nil {
			n := 0
			if lit, ok := e.Len.(*ast.BasicLit); ok {
				n, _ = strconv.Atoi(lit.Value)
			}
			if n <= 0 {
				return nil, false, errors.New("a fixed length that is not a literal count above zero")
			}
			if byteElem {
				return &xtype{kind: kFixed, n: n}, false, nil
			}
			elem, _, err := g.xdrType(e.Elt, 0)
			if err != nil || elem.kind > kBool {
				return nil, false, errors.New("a fixed-length array of a type other than an integer or a bool")
			}
			return &xtype{kind: kVector, n: n, elem: elem}, false, nil
		}
		if max == 0 {
			return nil, false, errors.New("a variable-length opaque or array with no maximum: tag it max=N")
		}
		if byteElem {
			return &xtype{kind: kOpaque, n: max}, true, nil
		}
		elem, _, err := g.xdrType(e.Elt, 0)
		if err != nil || elem.kind > kBool && elem.kind != kStruct {
			return nil, false, errors.New("a variable-length array of a type other than an integer, a bool or a struct")
		}
		return &xtype{kind: kArray, n: max, elem: elem}, true, nil
	case *ast.StarExpr:
		elem, _, err := g.xdrType(e.X, 0)
		if err != nil || elem.kind != kStruct {
			return nil, false, errors.New("optional data of a type other than a struct")
		}
		return &xtype{kind: kOptional, elem: elem}, false, nil
	case *ast.StructType:
		if len(e.Fields.List) == 0 {
			return &xtype{kind: kVoid}, false, nil
		}
	}
	return nil, false, fmt.Errorf("a type XDR's codec does not know: %s", types.ExprString(e))
}

// cycles refuses a type that holds itself.
//
// decision: such a type, an XDR linked list (RFC 4506 section 4.19), fails
// generation: no tag bounds it, so it has no MaxWire, and RFC 20 section 4.7's
// way out, a row passing its own Bound, is a row's, which the generator never
// sees. Overturned when the RFC states how a list's length is bounded.
func (g *gen) cycles() {
	state := map[string]int{} // 1 while its fields are walked, 2 after
	var walk func(s *strct)
	walk = func(s *strct) {
		state[s.name] = 1
		for _, f := range s.fields {
			for t := f.t; t != nil; t = t.elem {
				if t.kind != kStruct {
					continue
				}
				switch state[t.name] {
				case 1:
					g.errorf(f.pos, "%s.%s: a type that holds itself, which no maximum bounds", s.name, f.name)
				case 0:
					walk(g.byName[t.name])
				}
			}
		}
		state[s.name] = 2
	}
	for _, s := range g.structs {
		if state[s.name] == 0 {
			walk(s)
		}
	}
}
