// header begins every file the generator writes, and the inputs follow it,
// so a fresh run can be compared with the file checked in (RFC 20 section 5.1).
const header = "// Code generated by smb/wire/gen from "

const (
	wirePath      = "github.com/cubbit/dittofs/internal/adapter/smb/wire"
	resourcesPath = "github.com/cubbit/dittofs/pkg/resources"
)

type kind int

const (
	kInt     kind = iota // uint8 to uint64, or a type named over one
	kFixed               // [N]byte
	kBytes               // []byte
	kString              // string, UTF-16LE
	kUint16s             // []uint16
	kChain               // []T
	kArm                 // T, a union's arm
)

var widths = map[string]int{"uint8": 1, "uint16": 2, "uint32": 4, "uint64": 8}

// dialects are the dialects a since= may name, written as hex: those RFC 22
// section 3.1 serves. 2.0.2 is refused, so a field on the wire from it is on
// the wire in every dialect served and takes no since.
var dialects = []string{"0x210", "0x300", "0x302", "0x311"}

// allowed is the tags each kind of field may carry.
var allowed = map[kind][]string{
	kInt:     {"size", "empty", "name", "union", "since"},
	kFixed:   {"since"},
	kBytes:   {"offset", "len", "max", "align", "union", "default", "known", "since"},
	kString:  {"offset", "len", "max", "align", "utf16", "since"},
	kUint16s: {"count", "max", "since"},
	kChain:   {"offset", "len", "count", "max", "align", "chain", "since", "if"},
	kArm:     {"offset", "len", "align", "case", "exact", "since"},
}

type field struct {
	name string // "_" for a blank
	kind kind
	n    int    // a kInt's width, a kFixed's length
	typ  string // the type a kInt converts to; a kChain's or kArm's struct
	pos  token.Pos
	keys []string

	size                  int    // size=: a StructureSize
	label                 string // name=: a layout field's label
	offset, length, count string // the labels a variable field is located and sized by
	max                   int    // -1 when absent
	align                 int
	utf16, chain, union   bool
	exact                 bool   // an arm whose data is its struct's bytes, none past them
	empty                 bool   // a StructureSize whose variable part may be empty
	link                  string // chain=L
	cas                   string // case=
	def                   bool
	known                 []string // known=V|V: the default's values the server knows, with no arm of their own
	since                 string   // the dialect a field is on the wire from, as written; "" for every one
	from                  int      // since's dialect, 0 for every one
	ifList, ifValue       string   // if=L:V: on the wire only when the []uint16 field L holds V
}

// variable reports whether f follows the fixed part.
func (f *field) variable() bool { return f.kind >= kBytes }

type strct struct {
	name   string
	fields []*field
	kept   bool
}

// disc returns s's union discriminant, nil when it has none, and its arms,
// the default last.
func (s *strct) disc() (*field, []*field) {
	var d, def *field
	var arms []*field
	for _, f := range s.fields {
		switch {
		case f.union:
			d = f
		case f.kind == kArm:
			arms = append(arms, f)
		case f.def:
			def = f
		}
	}
	if def != nil {
		arms = append(arms, def)
	}
	return d, arms
}

type gen struct {
	fset    *token.FileSet
	structs []*strct
	byName  map[string]*strct
	shapes  map[string]*ast.StructType
	tagged  map[string]bool
	links   map[string]string // each chained member type and the label its members link by
	named   map[string]int    // the types named over an integer, by width
	errs    []error
}

func (g *gen) errorf(pos token.Pos, where, format string, args ...any) {
	g.errs = append(g.errs, fmt.Errorf("%s: %s: "+format, append([]any{g.fset.Position(pos), where}, args...)...))
}

// generate reads files, in dir, and returns the codec of every struct type
// they declare, or every field it cannot honour.
func generate(dir string, files []string) ([]byte, error) {
	g := &gen{fset: token.NewFileSet(), byName: map[string]*strct{}, shapes: map[string]*ast.StructType{}, tagged: map[string]bool{}, links: map[string]string{}, named: map[string]int{}}
	pkg := ""
	var specs []*ast.TypeSpec
	for _, name := range files {
		f, err := parser.ParseFile(g.fset, filepath.Join(dir, name), nil, 0)
		if err != nil {
			return nil, err
		}
		if pkg != "" && f.Name.Name != pkg {
			return nil, fmt.Errorf("%s: package %s, not %s", name, f.Name.Name, pkg)
		}
		pkg = f.Name.Name
		for _, decl := range f.Decls {
			if gd, ok := decl.(*ast.GenDecl); ok && gd.Tok == token.TYPE {
				for _, spec := range gd.Specs {
					specs = append(specs, spec.(*ast.TypeSpec))
				}
			}
		}
	}
	for _, ts := range specs {
		switch t := ts.Type.(type) {
		case *ast.StructType:
			s := &strct{name: ts.Name.Name}
			g.structs = append(g.structs, s)
			g.byName[s.name] = s
			g.shapes[s.name] = t
			for _, f := range t.Fields.List {
				if f.Tag != nil && strings.Contains(f.Tag.Value, "smb2:") {
					g.tagged[s.name] = true
				}
			}
		case *ast.Ident:
			if w := widths[t.Name]; w > 0 {
				g.named[ts.Name.Name] = w
			}
		}
	}
	// A file declares its wire structs and whatever else its handler needs
	// beside them: only a struct with a tagged field, and the ones a kept
	// struct holds as an arm or a chain, gain a codec; the rest the ops file
	// keeps to itself.
	var keep func(s *strct)
	keep = func(s *strct) {
		if s == nil || s.kept {
			return
		}
		s.kept = true
		for _, f := range g.shapes[s.name].Fields.List {
			if len(f.Names) != 1 {
				g.errorf(f.Pos(), s.name, "one name per field")
				continue
			}
			if fl := g.field(s.name, f); fl != nil {
				s.fields = append(s.fields, fl)
			}
		}
		for _, f := range s.fields {
			if f.kind == kChain && f.link != "" {
				g.links[f.typ] = f.link
			}
			if f.typ != "" && (f.kind == kArm || f.kind == kChain) {
				keep(g.byName[f.typ])
			}
		}
	}
	for _, s := range g.structs {
		if g.tagged[s.name] {
			keep(s)
		}
	}
	kept := slices.DeleteFunc(g.structs, func(s *strct) bool { return !s.kept })
	if len(kept) == 0 {
		return nil, errors.New("no wire struct to generate a codec for")
	}
	g.structs = kept
	for _, s := range g.structs {
		g.check(s)
	}
	if len(g.errs) == 0 {
		g.bounds()
	}
	if len(g.errs) > 0 {
		return nil, errors.Join(g.errs...)
	}
	return g.emit(pkg, files)
}

// field reads one field's type and tag.
func (g *gen) field(st string, f *ast.Field) *field {
	fl := &field{name: f.Names[0].Name, pos: f.Pos(), max: -1, align: 1}
	where := st + "." + fl.name
	switch t := f.Type.(type) {
	case *ast.Ident:
		switch {
		case widths[t.Name] > 0:
			fl.kind, fl.n = kInt, widths[t.Name]
		case g.named[t.Name] > 0:
			fl.kind, fl.n, fl.typ = kInt, g.named[t.Name], t.Name
		case t.Name == "string":
			fl.kind = kString
		case g.byName[t.Name] != nil:
			fl.kind, fl.typ = kArm, t.Name
		default:
			g.errorf(fl.pos, where, "a type it cannot encode, %s", t.Name)
			return nil
		}
	case *ast.ArrayType:
		elem, _ := t.Elt.(*ast.Ident)
		lit, _ := t.Len.(*ast.BasicLit)
		switch {
		case elem == nil:
		case t.Len == nil && elem.Name == "byte":
			fl.kind = kBytes
		case t.Len == nil && elem.Name == "uint16":
			fl.kind = kUint16s
		case t.Len == nil && g.byName[elem.Name] != nil:
			fl.kind, fl.typ = kChain, elem.Name
		case lit != nil && elem.Name == "byte":
			n, err := strconv.Atoi(lit.Value)
			if err == nil && n > 0 {
				fl.kind, fl.n = kFixed, n
				break
			}
			fallthrough
		default:
			elem = nil
		}
		if elem == nil {
			g.errorf(fl.pos, where, "an array or slice it cannot encode")
			return nil
		}
	default:
		g.errorf(fl.pos, where, "a type it cannot encode")
		return nil
	}
	if f.Tag == nil {
		return fl
	}
	raw, _ := strconv.Unquote(f.Tag.Value)
	tag, ok := reflect.StructTag(raw).Lookup("smb2")
	if !ok {
		return fl
	}
	for kv := range strings.SplitSeq(tag, ",") {
		k, v, _ := strings.Cut(kv, "=")
		num := func(least int) int {
			n, err := strconv.ParseInt(v, 0, 32)
			if err != nil || int(n) < least {
				g.errorf(fl.pos, where, "tag %s=%s is not a number of at least %d", k, v, least)
			}
			return int(n)
		}
		switch k {
		case "empty":
			fl.empty = true
		case "size":
			fl.size = num(1)
		case "name":
			fl.label = v
		case "offset":
			fl.offset = v
		case "len":
			fl.length = v
		case "count":
			fl.count = v
		case "max":
			fl.max = num(0)
		case "align":
			fl.align = num(1)
		case "utf16":
			fl.utf16 = true
		case "chain":
			fl.chain, fl.link = true, v
		case "union":
			fl.union = true
		case "case":
			fl.cas = v
		case "default":
			fl.def = true
		case "known":
			fl.known = strings.Split(v, "|")
		case "exact":
			fl.exact = true
		case "since":
			if !slices.Contains(dialects, v) {
				g.errorf(fl.pos, where, "tag since=%s is not a dialect served, one of %s", v, strings.Join(dialects, " "))
			}
			n, _ := strconv.ParseUint(strings.TrimPrefix(v, "0x"), 16, 16)
			fl.from, fl.since = int(n), v
		case "if":
			l, val, _ := strings.Cut(v, ":")
			if _, err := strconv.ParseUint(val, 0, 16); l == "" || err != nil {
				g.errorf(fl.pos, where, "tag if=%s is not L:V, a field and the uint16 it may hold", v)
			}
			fl.ifList, fl.ifValue = l, val
		default:
			g.errorf(fl.pos, where, "a tag it does not know, %q", k)
			continue
		}
		fl.keys = append(fl.keys, k)
	}
	return fl
}

// check fails each field of s whose tags the generator cannot honour.
func (g *gen) check(s *strct) {
	labels := map[string]*field{}
	users := map[string]*field{}  // the field each label locates or sizes
	before := map[string]*field{} // the named fields before this one
	unions := 0
	pastVariable := false
	for _, f := range s.fields {
		where := s.name + "." + f.name
		bad := func(format string, args ...any) { g.errorf(f.pos, where, format, args...) }
		// The list an if= reads is decoded before it, or the field would
		// never be read.
		if l := f.ifList; l != "" && (before[l] == nil || before[l].kind != kUint16s) {
			bad("if=%s names no []uint16 field before it", l)
		}
		before[f.name] = f
		// A fixed field after a variable one would decode from wherever the
		// variable field ended, not from its place in the struct's order.
		if pastVariable && !f.variable() {
			bad("a fixed field after a variable one")
		}
		if f.variable() {
			pastVariable = true
		}
		if f.union {
			if unions++; unions > 1 {
				bad("a second union discriminant")
			}
		}
		if f.variable() && f.name == "_" {
			bad("a variable field that is blank")
		}
		for _, k := range f.keys {
			if !slices.Contains(allowed[f.kind], k) {
				bad("a tag it cannot honour on this field's type, %q", k)
			}
		}
		for _, l := range []string{f.offset, f.length, f.count} {
			switch u := users[l]; {
			case l == "":
			case labels[l] == nil:
				bad("no layout field named %s before it", l)
			case labels[l].from > f.from:
				bad("its layout field %s on the wire in fewer dialects than it", l)
			case u != nil && (!arm(u) || !arm(f)):
				bad("a second field located or sized by %s", l)
			default:
				users[l] = f
			}
		}
		if f.align > 1 && f.offset == "" {
			bad("align without an offset")
		}
		switch f.kind {
		case kInt:
			switch {
			case (f.size > 0 || f.label != "") && f.name != "_":
				bad("size and name go on a blank field")
			case f.size > 0 && f.n != 2:
				bad("a StructureSize is a uint16")
			case f.empty && f.size%2 == 0:
				bad("empty on no odd StructureSize")
			case f.label != "" && f.n != 2 && f.n != 4:
				bad("a layout field is a uint16 or a uint32")
			case f.union && f.name == "_":
				bad("a union's discriminant is a named field")
			case labels[f.label] != nil:
				bad("a second layout field named %s", f.label)
			case f.label != "":
				labels[f.label] = f
			}
		case kBytes, kString:
			if f.length == "" {
				bad("a variable-length field with no len")
			}
			if f.kind == kString && !f.utf16 {
				bad("a string with no utf16")
			}
		case kUint16s:
			if f.count == "" {
				bad("a []uint16 with no count")
			}
		case kChain:
			g.checkChain(f, bad)
		case kArm:
			if f.cas == "" {
				bad("a struct field that is no union's arm: it has no case")
			}
		}
		if len(f.known) > 0 && !f.def {
			bad("known on no default arm")
		}
		if (f.kind == kArm || f.kind == kChain && f.link == "") && (f.typ == s.name || g.holds(g.byName[f.typ], s.name, map[string]bool{})) {
			bad("a type that holds itself, so no maximum")
		}
		if f.kind >= kBytes && f.kind <= kChain && f.max < 0 {
			bad("a variable-length field with no maximum")
		}
	}
	// A declared layout label no field names is never written: its struct
	// would answer whatever the wire sent to the offset it ignores. A chain
	// that links this struct's members by the label is a user of it.
	for _, f := range s.fields {
		if f.label != "" && users[f.label] == nil && g.links[s.name] != f.label {
			g.errorf(f.pos, s.name+"."+f.name, "a layout field no field uses")
		}
	}
	d, arms := s.disc()
	switch {
	case d == nil && len(arms) > 0:
		g.errorf(arms[0].pos, s.name+"."+arms[0].name, "an arm with no union discriminant")
	case d != nil && (len(arms) == 0 || !arms[len(arms)-1].def):
		g.errorf(d.pos, s.name+"."+d.name, "a union with no default arm")
	}
	for _, a := range arms {
		def := arms[len(arms)-1]
		if slices.Index(s.fields, a) < slices.Index(s.fields, d) {
			g.errorf(a.pos, s.name+"."+a.name, "an arm before its union's discriminant")
		}
		if a.offset != def.offset || a.length != def.length || a.align != def.align || a.since != def.since {
			g.errorf(a.pos, s.name+"."+a.name, "an arm not located as its union's default")
		}
		if a != def && g.fieldMax(a, map[string]bool{}) > def.max {
			g.errorf(a.pos, s.name+"."+a.name, "an arm whose maximum %d exceeds its union's default %d", g.fieldMax(a, map[string]bool{}), def.max)
		}
		if d != nil && d.kind == kInt {
			if _, err := strconv.ParseUint(a.cas, 0, 8*d.n); err != nil && !a.def {
				g.errorf(a.pos, s.name+"."+a.name, "a case its integer discriminant cannot hold, %q", a.cas)
			}
		}
	}
	if len(arms) == 0 || d == nil {
		return
	}
	def := arms[len(arms)-1]
	for _, k := range def.known {
		if d.kind == kInt {
			if _, err := strconv.ParseUint(k, 0, 8*d.n); err != nil {
				g.errorf(def.pos, s.name+"."+def.name, "a known value its integer discriminant cannot hold, %q", k)
			}
		}
		if slices.ContainsFunc(arms, func(a *field) bool { return a.cas == k }) {
			g.errorf(def.pos, s.name+"."+def.name, "a known value an arm takes, %q", k)
		}
	}
}

// arm reports whether f is an arm of its struct's union, which share one
// offset and length.
func arm(f *field) bool { return f.kind == kArm || f.def }

// checkChain fails a chain field whose tags do not say how its members follow.
func (g *gen) checkChain(f *field, bad func(string, ...any)) {
	switch {
	case !f.chain:
		bad("a []T with no chain")
	case f.offset == "":
		bad("a chain with no offset")
	case f.link == "" && (f.count == "" || f.length != ""):
		bad("a counted chain takes count, not len")
	case f.link != "" && (f.length == "" || f.count != ""):
		bad("a linked chain takes len, not count")
	case f.link == "" && f.align%8 != 0:
		// Its offset is written at its align, and its decoder refuses one
		// that is not a multiple of 8, where each member begins.
		bad("a counted chain aligned to %d, not a multiple of 8", f.align)
	case f.link != "":
		m := g.byName[f.typ]
		if len(m.fields) == 0 || m.fields[0].name != "_" || m.fields[0].n != 4 || m.fields[0].label != f.link {
			bad("a linked chain's member %s does not begin with a blank uint32 named %s", f.typ, f.link)
		}
	}
}

// fieldMax is the most f writes on the wire: a named struct's own bound, a
// raw or scalar arm its own width or maximum. A struct already being measured
// counts as nothing: it holds itself, and holds' own check refuses it.
func (g *gen) fieldMax(f *field, seen map[string]bool) int {
	if f.typ != "" {
		return g.structMax(g.byName[f.typ], seen)
	}
	return max(f.n, f.max)
}

// structMax is the most s ever writes on the wire, an upper bound over every
// dialect: fixed fields whole, since-gated fields counted too, a union's
// region one entry at its greatest member's width, a counted chain's members
// by the same depth. It backs the union arm check alone.
func (g *gen) structMax(s *strct, seen map[string]bool) int {
	if s == nil || seen[s.name] {
		return 0
	}
	seen[s.name] = true
	defer delete(seen, s.name)
	n, m, region := 0, 0, true
	_, arms := s.disc()
	for _, a := range arms {
		if w := g.fieldMax(a, seen); w > m {
			m = w
		}
	}
	for _, f := range s.fields {
		switch {
		case f.kind == kArm || f.def:
			if region {
				n += m
				region = false
			}
		case !f.variable():
			n += f.n
		case f.kind == kChain && f.link == "":
			n += f.align - 1 + f.max*(7+g.structMax(g.byName[f.typ], seen))
		default:
			n += f.align - 1 + f.max
		}
	}
	return n
}

// bounds refuses a struct whose largest encoding, counted as MaxWire counts
// it at the newest dialect, every field on the wire and nested maxima
// multiplied, passes 2^31-1 bytes. core adds a reply's MaxWire to its
// header's length and chain padding, so each bound under 2^31 keeps every
// such sum inside a 64-bit int. Each refusal names the innermost field that passes
// the bound, once. It runs once check refuses nothing, so no struct holds
// itself.
func (g *gen) bounds() {
	const over = uint64(math.MaxInt32) + 1                    // every sum and product saturates here
	add := func(a, b uint64) uint64 { return min(a+b, over) } // one side at most over: no wrap
	mul := func(a, b uint64) uint64 {
		if a != 0 && b > over/a {
			return over
		}
		return a * b
	}
	memo := map[string]uint64{}
	var str func(s *strct) uint64
	// part is what MaxWire adds for f, a field of s: a union's region once,
	// at its first arm, its default's padding and the greatest of its arms.
	part := func(s *strct, f *field) uint64 {
		if _, arms := s.disc(); f.kind == kArm || f.def {
			if f != arms[0] {
				return 0
			}
			def := arms[len(arms)-1]
			n := uint64(def.max)
			for _, a := range arms[:len(arms)-1] {
				n = max(n, str(g.byName[a.typ]))
			}
			return add(uint64(def.align-1), n)
		}
		switch f.kind {
		case kInt, kFixed:
			return uint64(f.n)
		case kBytes, kString:
			return add(uint64(f.align-1), uint64(f.max))
		case kUint16s:
			return mul(2, uint64(f.max))
		case kChain:
			if f.link != "" {
				return add(uint64(f.align-1), uint64(f.max))
			}
			return add(uint64(f.align-1), mul(uint64(f.max), add(7, str(g.byName[f.typ]))))
		}
		panic(fmt.Sprintf("gen: bounds has no size for kind %d", f.kind))
	}
	str = func(s *strct) uint64 {
		if n, ok := memo[s.name]; ok {
			return n
		}
		n := uint64(0)
		for _, f := range s.fields {
			n = add(n, part(s, f))
		}
		n = max(n, uint64(carried(s)))
		memo[s.name] = n
		return n
	}
	for _, s := range g.structs {
		if str(s) < over {
			continue
		}
		n := uint64(0)
		for _, f := range s.fields {
			if n = add(n, part(s, f)); n < over {
				continue
			}
			// A counted chain's member or a union's arm that passes the bound
			// is refused itself, so the field holding it is not the
			// innermost. A union's region past it by its own tags is named at
			// its default, whose max and align bound it.
			at, inner := f, f.kind == kChain && f.link == "" && str(g.byName[f.typ]) >= over
			if _, arms := s.disc(); f.kind == kArm || f.def {
				at = arms[len(arms)-1]
				inner = slices.ContainsFunc(arms, func(a *field) bool { return a.kind == kArm && str(g.byName[a.typ]) >= over })
			}
			if !inner {
				g.errorf(at.pos, s.name+"."+at.name, "a largest encoding past %d bytes, which MaxWire cannot bound: lower a max", math.MaxInt32)
			}
			break
		}
	}
}

// holds reports whether s holds the struct named name through an arm or a
// counted chain, whose maximum is its members', so MaxWire would not end.
func (g *gen) holds(s *strct, name string, seen map[string]bool) bool {
	if seen[s.name] {
		return false
	}
	seen[s.name] = true
	for _, f := range s.fields {
		if (f.kind == kArm || f.kind == kChain && f.link == "") && (f.typ == name || g.holds(g.byName[f.typ], name, seen)) {
			return true
		}
	}
	return false
}
