// header begins every file the generator writes, and the inputs follow it,
// so a fresh run can be compared with the file checked in (RFC 20 section 5.1).
const header = "// Code generated by smb/wire/gen from "

const (
	wirePath      = "github.com/cubbit/dittofs/internal/adapter/smb/wire"
	resourcesPath = "github.com/cubbit/dittofs/pkg/resources"
)

type kind int

const (
	kInt     kind = iota // uint8 to uint64, or a type named over one
	kFixed               // [N]byte
	kBytes               // []byte
	kString              // string, UTF-16LE
	kUint16s             // []uint16
	kChain               // []T
	kArm                 // T, a union's arm
)

var widths = map[string]int{"uint8": 1, "uint16": 2, "uint32": 4, "uint64": 8}

// allowed is the tags each kind of field may carry.
var allowed = map[kind][]string{
	kInt:     {"size", "empty", "name", "union", "since"},
	kFixed:   {"since"},
	kBytes:   {"offset", "len", "max", "align", "union", "default", "since"},
	kString:  {"offset", "len", "max", "align", "utf16", "since"},
	kUint16s: {"count", "max", "since"},
	kChain:   {"offset", "len", "count", "max", "align", "chain", "since"},
	kArm:     {"offset", "len", "align", "case", "exact", "since"},
}

type field struct {
	name string // "_" for a blank
	kind kind
	n    int    // a kInt's width, a kFixed's length
	typ  string // the type a kInt converts to; a kChain's or kArm's struct
	pos  token.Pos
	keys []string

	size                  int    // size=: a StructureSize
	label                 string // name=: a layout field's label
	offset, length, count string // the labels a variable field is located and sized by
	max                   int    // -1 when absent
	align                 int
	utf16, chain, union   bool
	exact                 bool   // an arm whose data is its struct's bytes, none past them
	empty                 bool   // a StructureSize whose variable part may be empty
	link                  string // chain=L
	cas                   string // case=
	def                   bool
	since                 string // the dialect a field is on the wire from, as written; "" for every one
}

// variable reports whether f follows the fixed part.
func (f *field) variable() bool { return f.kind >= kBytes }

type strct struct {
	name   string
	fields []*field
}

// disc returns s's union discriminant, nil when it has none, and its arms,
// the default last.
func (s *strct) disc() (*field, []*field) {
	var d, def *field
	var arms []*field
	for _, f := range s.fields {
		switch {
		case f.union:
			d = f
		case f.kind == kArm:
			arms = append(arms, f)
		case f.def:
			def = f
		}
	}
	if def != nil {
		arms = append(arms, def)
	}
	return d, arms
}

type gen struct {
	fset    *token.FileSet
	structs []*strct
	byName  map[string]*strct
	named   map[string]int // the types named over an integer, by width
	errs    []error
}

func (g *gen) errorf(pos token.Pos, where, format string, args ...any) {
	g.errs = append(g.errs, fmt.Errorf("%s: %s: "+format, append([]any{g.fset.Position(pos), where}, args...)...))
}

// generate reads files, in dir, and returns the codec of every struct type
// they declare, or every field it cannot honour.
func generate(dir string, files []string) ([]byte, error) {
	g := &gen{fset: token.NewFileSet(), byName: map[string]*strct{}, named: map[string]int{}}
	pkg := ""
	var specs []*ast.TypeSpec
	for _, name := range files {
		f, err := parser.ParseFile(g.fset, filepath.Join(dir, name), nil, 0)
		if err != nil {
			return nil, err
		}
		if pkg != "" && f.Name.Name != pkg {
			return nil, fmt.Errorf("%s: package %s, not %s", name, f.Name.Name, pkg)
		}
		pkg = f.Name.Name
		for _, decl := range f.Decls {
			if gd, ok := decl.(*ast.GenDecl); ok && gd.Tok == token.TYPE {
				for _, spec := range gd.Specs {
					specs = append(specs, spec.(*ast.TypeSpec))
				}
			}
		}
	}
	for _, ts := range specs {
		switch t := ts.Type.(type) {
		case *ast.StructType:
			s := &strct{name: ts.Name.Name}
			g.structs = append(g.structs, s)
			g.byName[s.name] = s
		case *ast.Ident:
			if w := widths[t.Name]; w > 0 {
				g.named[ts.Name.Name] = w
			}
		}
	}
	for _, ts := range specs {
		if st, ok := ts.Type.(*ast.StructType); ok {
			s := g.byName[ts.Name.Name]
			for _, f := range st.Fields.List {
				if len(f.Names) != 1 {
					g.errorf(f.Pos(), s.name, "one name per field")
					continue
				}
				if fl := g.field(s.name, f); fl != nil {
					s.fields = append(s.fields, fl)
				}
			}
		}
	}
	for _, s := range g.structs {
		g.check(s)
	}
	if len(g.errs) > 0 {
		return nil, errors.Join(g.errs...)
	}
	return g.emit(pkg, files)
}

// field reads one field's type and tag.
func (g *gen) field(st string, f *ast.Field) *field {
	fl := &field{name: f.Names[0].Name, pos: f.Pos(), max: -1, align: 1}
	where := st + "." + fl.name
	switch t := f.Type.(type) {
	case *ast.Ident:
		switch {
		case widths[t.Name] > 0:
			fl.kind, fl.n = kInt, widths[t.Name]
		case g.named[t.Name] > 0:
			fl.kind, fl.n, fl.typ = kInt, g.named[t.Name], t.Name
		case t.Name == "string":
			fl.kind = kString
		case g.byName[t.Name] != nil:
			fl.kind, fl.typ = kArm, t.Name
		default:
			g.errorf(fl.pos, where, "a type it cannot encode, %s", t.Name)
			return nil
		}
	case *ast.ArrayType:
		elem, _ := t.Elt.(*ast.Ident)
		lit, _ := t.Len.(*ast.BasicLit)
		switch {
		case elem == nil:
		case t.Len == nil && elem.Name == "byte":
			fl.kind = kBytes
		case t.Len == nil && elem.Name == "uint16":
			fl.kind = kUint16s
		case t.Len == nil && g.byName[elem.Name] != nil:
			fl.kind, fl.typ = kChain, elem.Name
		case lit != nil && elem.Name == "byte":
			n, err := strconv.Atoi(lit.Value)
			if err == nil && n > 0 {
				fl.kind, fl.n = kFixed, n
				break
			}
			fallthrough
		default:
			elem = nil
		}
		if elem == nil {
			g.errorf(fl.pos, where, "an array or slice it cannot encode")
			return nil
		}
	default:
		g.errorf(fl.pos, where, "a type it cannot encode")
		return nil
	}
	if f.Tag == nil {
		return fl
	}
	raw, _ := strconv.Unquote(f.Tag.Value)
	tag, ok := reflect.StructTag(raw).Lookup("smb2")
	if !ok {
		return fl
	}
	for kv := range strings.SplitSeq(tag, ",") {
		k, v, _ := strings.Cut(kv, "=")
		num := func(least int) int {
			n, err := strconv.ParseInt(v, 0, 32)
			if err != nil || int(n) < least {
				g.errorf(fl.pos, where, "tag %s=%s is not a number of at least %d", k, v, least)
			}
			return int(n)
		}
		switch k {
		case "empty":
			fl.empty = true
		case "size":
			fl.size = num(1)
		case "name":
			fl.label = v
		case "offset":
			fl.offset = v
		case "len":
			fl.length = v
		case "count":
			fl.count = v
		case "max":
			fl.max = num(0)
		case "align":
			fl.align = num(1)
		case "utf16":
			fl.utf16 = true
		case "chain":
			fl.chain, fl.link = true, v
		case "union":
			fl.union = true
		case "case":
			fl.cas = v
		case "default":
			fl.def = true
		case "exact":
			fl.exact = true
		case "since":
			num(0)
			fl.since = v
		default:
			g.errorf(fl.pos, where, "a tag it does not know, %q", k)
			continue
		}
		fl.keys = append(fl.keys, k)
	}
	return fl
}

// check fails each field of s whose tags the generator cannot honour.
func (g *gen) check(s *strct) {
	labels := map[string]*field{}
	unions := 0
	for _, f := range s.fields {
		where := s.name + "." + f.name
		bad := func(format string, args ...any) { g.errorf(f.pos, where, format, args...) }
		if f.union {
			if unions++; unions > 1 {
				bad("a second union discriminant")
			}
		}
		if f.variable() && f.name == "_" {
			bad("a variable field that is blank")
		}
		for _, k := range f.keys {
			if !slices.Contains(allowed[f.kind], k) {
				bad("a tag it cannot honour on this field's type, %q", k)
			}
		}
		for _, l := range []string{f.offset, f.length, f.count} {
			if l != "" && labels[l] == nil {
				bad("no layout field named %s before it", l)
			}
		}
		if f.align > 1 && f.offset == "" {
			bad("align without an offset")
		}
		switch f.kind {
		case kInt:
			switch {
			case (f.size > 0 || f.label != "") && f.name != "_":
				bad("size and name go on a blank field")
			case f.size > 0 && f.n != 2:
				bad("a StructureSize is a uint16")
			case f.empty && f.size%2 == 0:
				bad("empty on no odd StructureSize")
			case f.label != "" && f.n != 2 && f.n != 4:
				bad("a layout field is a uint16 or a uint32")
			case f.union && f.name == "_":
				bad("a union's discriminant is a named field")
			case labels[f.label] != nil:
				bad("a second layout field named %s", f.label)
			case f.label != "":
				labels[f.label] = f
			}
		case kBytes, kString:
			if f.length == "" {
				bad("a variable-length field with no len")
			}
			if f.kind == kString && !f.utf16 {
				bad("a string with no utf16")
			}
		case kUint16s:
			if f.count == "" {
				bad("a []uint16 with no count")
			}
		case kChain:
			g.checkChain(f, bad)
		case kArm:
			if f.cas == "" {
				bad("a struct field that is no union's arm: it has no case")
			}
		}
		if (f.kind == kArm || f.kind == kChain && f.link == "") && (f.typ == s.name || g.holds(g.byName[f.typ], s.name, map[string]bool{})) {
			bad("a type that holds itself, so no maximum")
		}
		if f.kind >= kBytes && f.kind <= kChain && f.max < 0 {
			bad("a variable-length field with no maximum")
		}
	}
	d, arms := s.disc()
	switch {
	case d == nil && len(arms) > 0:
		g.errorf(arms[0].pos, s.name+"."+arms[0].name, "an arm with no union discriminant")
	case d != nil && (len(arms) == 0 || !arms[len(arms)-1].def):
		g.errorf(d.pos, s.name+"."+d.name, "a union with no default arm")
	}
	for _, a := range arms {
		def := arms[len(arms)-1]
		if slices.Index(s.fields, a) < slices.Index(s.fields, d) {
			g.errorf(a.pos, s.name+"."+a.name, "an arm before its union's discriminant")
		}
		if a.offset != def.offset || a.length != def.length || a.align != def.align || a.since != def.since {
			g.errorf(a.pos, s.name+"."+a.name, "an arm not located as its union's default")
		}
		if d != nil && d.kind == kInt {
			if _, err := strconv.ParseUint(a.cas, 0, 8*d.n); err != nil && !a.def {
				g.errorf(a.pos, s.name+"."+a.name, "a case its integer discriminant cannot hold, %q", a.cas)
			}
		}
	}
}

// checkChain fails a chain field whose tags do not say how its members follow.
func (g *gen) checkChain(f *field, bad func(string, ...any)) {
	switch {
	case !f.chain:
		bad("a []T with no chain")
	case f.offset == "":
		bad("a chain with no offset")
	case f.link == "" && (f.count == "" || f.length != ""):
		bad("a counted chain takes count, not len")
	case f.link != "" && (f.length == "" || f.count != ""):
		bad("a linked chain takes len, not count")
	case f.link != "":
		m := g.byName[f.typ]
		if len(m.fields) == 0 || m.fields[0].name != "_" || m.fields[0].n != 4 || m.fields[0].label != f.link {
			bad("a linked chain's member %s does not begin with a blank uint32 named %s", f.typ, f.link)
		}
	}
}

// holds reports whether s holds the struct named name through an arm or a
// counted chain, whose maximum is its members', so MaxWire would not end.
func (g *gen) holds(s *strct, name string, seen map[string]bool) bool {
	if seen[s.name] {
		return false
	}
	seen[s.name] = true
	for _, f := range s.fields {
		if (f.kind == kArm || f.kind == kChain && f.link == "") && (f.typ == name || g.holds(g.byName[f.typ], name, seen)) {
			return true
		}
	}
	return false
}
